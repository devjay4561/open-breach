// Picks `${field}_en` off a data object (ROSTER/VARIANTS/MODIFIERS/
// EQUIPMENT/WEAPONS entries in meta.js, or mission catalog entries from the
// engine) when in English mode and the field is present, else the Korean
// base field. Used instead of a static dict because these are data-driven
// lists, not fixed UI chrome strings.
export function localize(item, field) {
  if (!item) return '';
  if (currentLang === 'en' && item[`${field}_en`] != null) return item[`${field}_en`];
  return item[field];
}

export function t(key, params) {
  const dict = DICTS[currentLang] || DICTS.ko;
  let value = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : DICTS.ko[key];
  if (value == null) return key;
  if (params) for (const name of Object.keys(params)) value = value.replaceAll(`{${name}}`, String(params[name]));
  return value;
}


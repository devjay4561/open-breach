// Translates a Godot simulation event for display in the operation log.
// `event.type` is the stable code; `event.kind` (when present) is a second
// stable code for sub-actions (e.g. the door-action enum). Anything without
// an English mapping falls back to the Korean message the engine sent, so
// the log never goes blank in English mode.
export function translateEvent(event, ctx = {}) {
  if (['FRAG_RELEASE', 'FRAG'].includes(event?.type)) return event.observed === true ? t(`event.${event.type}`) : '';
  if (['CALL_CLEAR', 'CALL_ROOM_CLEAR', 'CALL_SHORT_ROOM', 'CALL_RELOADING', 'CALL_GUN_UP', 'CALL_MAN_DOWN'].includes(event?.type)) {
    if (event.observed !== true) return '';
    // New team calls never use a raw engine message or unknown actor ID.
    // The caller supplies names only for own operators and observed rooms.
    const unit = ctx.ownUnitName?.(eventUnitId(event)) || '';
    const room = ctx.observedRoomName?.(event.room_id ?? event.extra?.room_id) || '';
    const cover = event.type === 'CALL_RELOADING' ? ctx.ownUnitName?.(event.cover_unit_id ?? event.extra?.cover_unit_id) || '' : '';
    return [unit, t(`event.${event.type}`), room, cover ? t('team.covering', { name: cover }) : ''].filter(Boolean).join(' · ');
  }
  if (['KICK_FAILED', 'BREACH_RETREAT'].includes(event?.type)) return t(`event.${event.type}`);
  if (currentLang !== 'en') return event?.message || '';
  const type = event?.type || '';
  const kind = eventKind(event);
  if (type === 'DOOR_ACTION') return `Door · ${DOOR_ACTION_EN[kind] || DOOR_ACTION_EN[event?.message?.split('·')?.[1]?.trim()] || kind || event.message}`;
  const template = EVENT_EN[type];
  if (template) {
    const resolvedCtx = { unitName: id => (ctx.unitName ? ctx.unitName(id) : id) || id, missionName: ctx.missionName || '' };
    return template(event, resolvedCtx);
  }
  return event?.message || '';
}

// Applies `data-i18n` (textContent), `data-i18n-html` (innerHTML, for
// strings with inline <kbd>/<br>) and `data-i18n-attr-*` (attribute text)
// to every element currently in the DOM. Called on boot and whenever the
// language setting changes so static chrome updates live, no reload.
export function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
}

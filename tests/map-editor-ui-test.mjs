import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
const source=await readFile(new URL('../web/map-editor.js',import.meta.url),'utf8');
const css=await readFile(new URL('../web/style.css',import.meta.url),'utf8');
const browser=await chromium.launch({headless:true,...(process.env.BREACH_CHANNEL?{channel:process.env.BREACH_CHANNEL}:{}),...(process.env.BREACH_EXECUTABLE_PATH?{executablePath:process.env.BREACH_EXECUTABLE_PATH}:{})});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
let checks=0;
try {
  await page.setContent(`<style>${css}</style><dialog id="modal"><header><div><span class="eyebrow">MAP EDITOR</span><h2>지도 편집</h2></div></header><div id="modal-content"></div></dialog>`);
  await page.evaluate(async source=>{
    const editor=await import('data:text/javascript;base64,'+btoa(unescape(encodeURIComponent(source))));
    const mission=editor.createEditorMission();
    mission.enemies[0].spawns=[{x:11,z:3,facing:1,patrol:[[11,3],[12,3]]}];
    const root=document.querySelector('#modal-content');root.innerHTML=editor.renderMapEditor(mission);
    window.calls={play:[],exports:[],imports:[],toasts:[]};
    window.editor=editor.bindMapEditor(root,{mission,onPlay:data=>window.calls.play.push(data),onExport:(data,name)=>window.calls.exports.push({data,name}),onImportFile:(file,data)=>window.calls.imports.push(data),toast:(message,type)=>window.calls.toasts.push({message,type})});
    document.querySelector('#modal').showModal();
  },source);
  const clickWorld=async(x,z)=>{
    const canvas=page.locator('[data-editor-canvas]'),box=await canvas.boundingBox();
    const bounds=await page.evaluate(()=>window.editor.getMission().bounds);
    const scale=Math.min(600/bounds[0],320/bounds[1]);
    await canvas.click({position:{x:((640-bounds[0]*scale)/2+x*scale)*box.width/640,y:((360-bounds[1]*scale)/2+z*scale)*box.height/360}});
  };
  assert.equal(await page.locator('[data-editor-play]').isEnabled(),true);checks++;
  await page.locator('[data-editor-tool="props"]').click();
  await clickWorld(6,6);
  assert.equal(await page.evaluate(()=>window.editor.getMission().props.length),1);checks++;
  await page.locator('[data-editor-field="type"]').selectOption('desk');
  await page.locator('[data-editor-field="cover"]').selectOption('full');
  assert.equal(await page.evaluate(()=>window.editor.getMission().props[0].cover),'full');checks++;
  await page.locator('[data-editor-field="x"]').fill('5');
  await page.locator('[data-editor-field="x"]').press('Tab');
  assert.equal(await page.evaluate(()=>window.editor.getMission().props[0].x),5);checks++;
  await page.locator('[data-editor-field="height"]').fill('1.6');
  await page.locator('[data-editor-field="height"]').press('Tab');
  await page.locator('[data-editor-field="material"]').selectOption('metal');
  assert.equal(await page.evaluate(()=>window.editor.getMission().props[0].height),1.6);checks++;
  assert.equal(await page.evaluate(()=>window.editor.getMission().props[0].material),'metal');checks++;
  await page.locator('[data-editor-environment]').selectOption('night');
  assert.deepEqual(await page.evaluate(()=>window.editor.getMission().environment),{time_of_day:'night',lighting:.25});checks++;
  await page.locator('[data-editor-tool="doors"]').click();await clickWorld(8,8);
  await page.locator('[data-editor-field="hinge_side"]').selectOption('1');
  await page.locator('[data-editor-field="locked"]').check();
  await page.locator('[data-editor-field="state"]').selectOption('AJAR');
  await page.locator('[data-editor-field="progress"]').fill('0.2');await page.locator('[data-editor-field="progress"]').press('Tab');
  assert.equal(await page.evaluate(()=>window.editor.getMission().doors[0].hinge_side),1);checks++;
  assert.equal(await page.evaluate(()=>window.editor.getMission().doors[0].locked),true);checks++;
  assert.equal(await page.evaluate(()=>window.editor.getMission().doors[0].progress),.2);checks++;
  await page.locator('[data-editor-preset]').selectOption('stealth');
  assert.equal(await page.evaluate(()=>window.editor.getMission().fail.some(rule=>rule.type==='before_alert')),true);checks++;
  assert.equal(await page.evaluate(()=>window.editor.getMission().enemies[0].spawns[0].patrol.length),2);checks++;
  await page.locator('[data-editor-export]').click();
  assert.equal(await page.evaluate(()=>window.calls.exports[0].data.props[0].type),'desk');checks++;
  await page.locator('[data-editor-play]').click();
  assert.equal(await page.evaluate(()=>window.calls.play[0].variant),'infiltration');checks++;
  await page.locator('[data-editor-tool="select"]').click();
  await clickWorld(5,6);
  await page.locator('[data-editor-canvas]').press('Delete');
  assert.equal(await page.evaluate(()=>window.editor.getMission().props.length),0);checks++;
  const imported=await page.evaluate(()=>({...window.editor.getMission(),title:'가져온 지도',seed:20261007}));
  await page.locator('[data-editor-file]').setInputFiles({name:'mission.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))});
  await page.waitForFunction(()=>window.calls.imports.length===1);
  assert.equal(await page.locator('[data-editor-title]').inputValue(),'가져온 지도');checks++;
  await page.locator('.editor-json summary').click();
  const text=await page.locator('[data-editor-json]').inputValue();
  const invalid=JSON.parse(text);invalid.win=[{type:'unknown_rule'}];
  await page.locator('[data-editor-json]').fill(JSON.stringify(invalid));
  await page.locator('[data-editor-apply]').click();
  assert.equal(await page.evaluate(()=>window.calls.toasts.at(-1).type),'error');checks++;
  assert.notEqual(await page.evaluate(()=>window.editor.getMission().win[0].type),'unknown_rule');checks++;
  await page.locator('[data-editor-json]').fill(text);
  await page.locator('[data-editor-apply]').click();
  await page.locator('.editor-json summary').click();
  await mkdir(new URL('./artifacts/',import.meta.url),{recursive:true});
  await page.screenshot({path:new URL('./artifacts/map-editor-ui.png',import.meta.url).pathname});
  assert.deepEqual(errors,[]);checks++;
  console.log(`Map editor UI: ${checks} checks passed`);
} finally {await browser.close();}

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const meta=await import('data:text/javascript;base64,'+Buffer.from(await readFile(new URL('../web/meta.js',import.meta.url))).toString('base64'));
let checks=0;
const check=(actual,expected)=>{assert.deepEqual(actual,expected);checks++;};
check(meta.migrateMedals([true,false,true]),{complete:true,survival:false,par_time:true});
check(meta.migrateMedals({no_hits:true,no_stun:false}),{no_hits:true,no_stun:false});
check(meta.migrateMedals(null),{});
check(meta.mergeStars({medals:[true,false,false]},[{id:'no_hits',done:true}]),{complete:true,survival:false,par_time:false,no_hits:true});
check(meta.mergeStars({stars:{no_hits:true}},[{id:'no_hits',done:false}]),{no_hits:true});
check(meta.totalStars([{id:'M01',stars:{no_hits:true,no_stun:true}},{id:'run:x',kind:'run',stars:{no_hits:true}},{id:'campaign',kind:'campaign'}]),2);
const starRecords=new Map([['M01',{id:'M01',medals:[true,false,true]}],['run:x',{id:'run:x',stars:{no_hits:true}}],['campaign',{id:'campaign',stars:{complete:true}}],['M02',{id:'M02',kind:'run',stars:{complete:true}}]]);
check(meta.totalStars(starRecords),2);
starRecords.get('M01').medals=[false,true,false];check(meta.totalStars(starRecords),1);
starRecords.set('M03',{id:'M03',kind:'mission',stars:{complete:true,invalid:'true',survival:false}});check(meta.totalStars(starRecords),2);
check(meta.totalStars(null),0);
check(meta.missionId('M01','challenge','standard'),'M01H');
check(meta.missionId('M01H','challenge','escort'),'M01_ESCORT');
check(meta.missionId('T01','challenge','escort'),'T01');
check(meta.missionBase('M03_INFILTRATION'),'M03');
check(meta.missionId('H01','challenge','escort'),'H01');
check(meta.missionBase('H36'),'H36');
const a={mission:'M01',seed:42,variant:'arrest',modifiers:['night','no_stun'],loadout:{alpha:{weapon:'standard',equipment:{stun:1,smoke:0}}}};
const b={...a,modifiers:['no_stun','night','night'],loadout:{alpha:{equipment:{smoke:0,stun:1},weapon:'standard'}}};
check(meta.conditionKey(a),meta.conditionKey(b));
check(meta.conditionKey(a)===meta.conditionKey({...a,seed:43}),false);
check(meta.conditionKey(a)===meta.conditionKey({...a,variant:'standard'}),false);
check(meta.conditionKey({...a,variant:'standard'}),meta.conditionKey({...a,variant:'normal'}));
check(meta.conditionKey(a)===meta.conditionKey({...a,loadout:{alpha:{weapon:'light'}}}),false);
check(meta.dailyOperation('2026-10-07'),meta.dailyOperation('2026-10-07'));
check(meta.dailyOperation('2026-10-07').seed===meta.dailyOperation('2026-10-08').seed,false);
check(meta.dailyOperation('2026-10-07').seed>0,true);
check(meta.dailyOperation('2026-10-07').seed<=2147483647,true);
check(meta.localDate(new Date(2026,9,7)),'2026-10-07');
let campaign=meta.newCampaign(true);
check(campaign.mission,'M01');
check(meta.availableRoster(campaign).length,8);
const state={mission:'M01',seed:1,result:{success:true,stuns_used:2,breaches_used:1,losses:1},units:[{id:'alpha',roster_id:'raven',hp:30},{id:'bravo',roster_id:'echo',hp:0},{id:'charlie',roster_id:'moss',hp:80}]};
campaign=meta.finishCampaign(campaign,state);
check(campaign.mission,'M02');
check(campaign.injured,['raven']);
check(campaign.lost,['echo']);
check(campaign.inventory,{stun:14,breach:7});
check(meta.availableRoster(campaign).length,6);
const failed=meta.finishCampaign(meta.newCampaign(true),{...state,result:{success:false,stuns_used:3,breaches_used:1},units:[{id:'alpha',roster_id:'raven',hp:0},{id:'bravo',roster_id:'echo',hp:20}]});
check(failed.index,0);check(failed.mission,'M01');check(failed.inventory,{stun:13,breach:7});check(failed.lost,['raven']);check(failed.injured,['echo']);check(meta.availableRoster(failed).length,6);
check(meta.checkCampaignLoadout(campaign,{alpha:{equipment:{stun:17}}})?.includes('부족'),true);
check(meta.checkCampaignLoadout(campaign,{alpha:{equipment:{stun:14,breach:7}}}),null);
const restored=JSON.parse(JSON.stringify(campaign));check(restored,campaign);
campaign=meta.finishCampaign(restored,{...state,mission:'M02',units:[{id:'alpha',roster_id:'moss',hp:100}]});
check(campaign.mission,'M03');check(campaign.injured,[]);check(campaign.lost,['echo']);
campaign=meta.finishCampaign(campaign,{...state,mission:'M03',units:[]});
check(campaign.active,true);check(campaign.index,3);check(campaign.mission,'M04');
for(const mission of meta.CAMPAIGN_MISSIONS.slice(3)) campaign=meta.finishCampaign(campaign,{...state,mission,units:[]});
check(campaign.active,false);check(campaign.index,meta.CAMPAIGN_MISSIONS.length);check(campaign.history.length,meta.CAMPAIGN_MISSIONS.length);
const legacy=meta.newCampaign();delete legacy.missions;legacy.index=2;legacy.mission='M03';
check(meta.finishCampaign(legacy,{...state,mission:'M03',units:[]}).active,false);
check(meta.missionId('M04','challenge','escort'),'M04H');
check(meta.missionId('M09','challenge','escort'),'M09H');
check(meta.missionBase('M08H'),'M08');
check(meta.VARIANTS.some(item=>item.id==='arrest'),false);
const normal=meta.finishCampaign(meta.newCampaign(false),state);check(normal.lost,[]);check(normal.injured,['raven','echo']);
check(meta.EQUIPMENT.every(item=>Number.isInteger(item.stars)&&item.stars>=0),true);
check(meta.ROSTER.every(item=>['breacher','marksman','cautious','rescuer'].includes(item.trait)),true);
const preparation={roster:[{id:'raven',base_id:'alpha',trait:'breacher'},{id:'echo',base_id:'bravo',trait:'marksman'}],loadout:{alpha:{weapon:'standard',equipment:{stun:1}},bravo:{weapon:'light',equipment:{stun:1}}}};
const emptyLegacy=meta.normalizeCampaignPlan({units:[],roster:[],loadout:{}},preparation,meta.newCampaign(true));
check(emptyLegacy.roster,preparation.roster);check(emptyLegacy.loadout,preparation.loadout);
const absentLegacy=meta.normalizeCampaignPlan({units:[]},preparation,meta.newCampaign(true));check(absentLegacy.roster[0].id,'raven');check(absentLegacy.loadout.alpha.equipment.stun,1);
const none=meta.normalizeCampaignPlan({loadout:{alpha:{weapon:'light',equipment:{}},bravo:{equipment:{}}}},preparation,{...meta.newCampaign(),inventory:{stun:0,breach:0}});check(none.loadout.alpha.equipment,{});check(none.loadout.bravo.equipment,{});check(none.loadout.alpha.weapon,'light');
const partial=meta.normalizeCampaignPlan({loadout:{alpha:{weapon:'light'}}},preparation,meta.newCampaign());check(partial.loadout.alpha.equipment,{stun:1});check(partial.loadout.bravo.equipment,{stun:1});
const arrayGear=meta.normalizeCampaignPlan({loadout:{alpha:{equipment:['stun','breach']}}},preparation,meta.newCampaign());check(arrayGear.loadout.alpha.equipment,{stun:1,smoke:0,breach:1});
assert.throws(()=>meta.normalizeCampaignPlan({loadout:{}},preparation,{...meta.newCampaign(),inventory:{stun:1,breach:4}}),/재고가 부족/);checks++;
assert.throws(()=>meta.normalizeCampaignPlan({roster:[{id:'raven',base_id:'alpha'}]},preparation,{...meta.newCampaign(true),lost:['raven']}),/사용할 수 없는/);checks++;
assert.throws(()=>meta.normalizeCampaignPlan({roster:[{id:'unknown',base_id:'alpha'}]},preparation,meta.newCampaign()),/사용할 수 없는/);checks++;
console.log(`Meta: ${checks} checks passed`);
